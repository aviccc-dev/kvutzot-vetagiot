def N(name, src='', d=None, p=None, ex=None, r=None, h=None, note=None, divs=None):
    return dict(name=name, src=src, d=d, p=p, ex=ex, r=r, h=h or [], note=note, divs=divs or [])

def D(aspect, *kids):
    return (aspect, list(kids))

def L(x):
    if x is None: return []
    return x if isinstance(x, list) else [x]

